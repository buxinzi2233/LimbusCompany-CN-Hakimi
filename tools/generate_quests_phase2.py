for name, qdict in file_map.items():
    kr_p = f"backups/part2-scope-20260924/source-kr/RPGSystem/rpg-loc-quest-{name}.json"
    with open(kr_p, encoding="utf-8") as f:
        kr_json = json.load(f)
    out_list = []
    for kr_q in kr_json["dataList"]:
        k = kr_q["key"]
        if k not in qdict:
            raise ValueError(f"Missing translation for quest key {k} in {name}")
        t = qdict[k]
        new_q = {"key": k}
        if "title" in kr_q:
            new_q["title"] = t.get("title", kr_q["title"])
        if "description" in kr_q:
            new_q["description"] = t.get("description", kr_q["description"])
        if "steps" in kr_q:
            new_steps = []
            for s_idx, s in enumerate(kr_q["steps"]):
                ns = dict(s)
                if "goalDescription1" in s:
                    t_steps = t.get("steps", [])
                    if s_idx < len(t_steps):
                        ns["goalDescription1"] = t_steps[s_idx]
                    else:
                        ns["goalDescription1"] = s["goalDescription1"]
                new_steps.append(ns)
            new_q["steps"] = new_steps
        out_list.append(new_q)
    
    zh_p = f"workspace/LLC_zh-CN/RPGSystem/rpg-loc-quest-{name}.json"
    with open(zh_p, "w", encoding="utf-8") as f:
        json.dump({"dataList": out_list}, f, ensure_ascii=False, indent=2)
        f.write("\n")
    print(f"Generated {zh_p} with {len(out_list)} quests.")
